"""Draw the home page's hero chart: the statistical significance filter.

    python scripts/make_hero.py

Writes _hero-chart.md, a raw-HTML block with an inline SVG that index.qmd
includes. The chart is the same experiment as the Statistical Significance
Filter entry (true effect 0.2, standard error 0.25), replicated N times, with
the significant estimates in red. It is drawn once, here, so the home page
needs no JavaScript or Observable runtime to show it; CSS in styles.css
animates the dots in (and doesn't, for readers who ask for reduced motion).
The caption's numbers are computed from the same draws.
"""

import os
import random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THETA, SE, N, SEED = 0.2, 0.25, 120, 32

W, H = 600, 380
LEFT, RIGHT, TOP, BOTTOM = 46, 18, 40, 44
Y_LO, Y_HI = -0.9, 1.1
BLUE, RED, GRAY = "#2166ac", "#d6604d", "#8a8a8a"


def main():
    rng = random.Random(SEED)
    est = [rng.gauss(THETA, SE) for _ in range(N)]
    cut = 1.96 * SE
    sig = [abs(e) > cut for e in est]
    k = sum(sig)
    sig_est = [e for e, s in zip(est, sig) if s]
    ratio = sum(abs(e) for e in sig_est) / k / THETA
    wrong = sum(1 for e in sig_est if e < 0)
    assert k >= 8 and all(abs(e) > THETA for e in sig_est), (k, sig_est)

    def x(i):
        return LEFT + (W - LEFT - RIGHT) * (i + 0.5) / N

    def y(v):
        v = max(Y_LO, min(Y_HI, v))
        return TOP + (H - TOP - BOTTOM) * (Y_HI - v) / (Y_HI - Y_LO)

    parts = []
    # Zone where estimates are not significant.
    parts.append(f'<rect class="hero-band" x="{LEFT}" y="{y(cut):.1f}" width="{W - LEFT - RIGHT}" '
                 f'height="{y(-cut) - y(cut):.1f}" />')
    parts.append(f'<text class="hero-band-label" x="{W - RIGHT - 6}" y="{y(-cut) - 8:.1f}" '
                 f'text-anchor="end">not significant</text>')
    # Axis ticks.
    for v in [-0.5, 0, 0.5, 1.0]:
        parts.append(f'<text class="hero-tick" x="{LEFT - 8}" y="{y(v) + 4:.1f}" text-anchor="end">{v:g}</text>')
    parts.append(f'<line class="hero-zero" x1="{LEFT}" x2="{W - RIGHT}" y1="{y(0):.1f}" y2="{y(0):.1f}" />')
    # Dots, appearing left to right.
    for i, (e, s) in enumerate(zip(est, sig)):
        cls = "hero-dot sig" if s else "hero-dot"
        r = 5.6 if s else 3.6
        parts.append(f'<circle class="{cls}" style="--i:{i}" cx="{x(i):.1f}" cy="{y(e):.1f}" r="{r}" />')
    # True effect, drawn last so it sits on top.
    parts.append(f'<line class="hero-truth" x1="{LEFT}" x2="{W - RIGHT}" y1="{y(THETA):.1f}" y2="{y(THETA):.1f}" />')
    parts.append(f'<text class="hero-truth-label" x="{W - RIGHT - 4}" y="{y(THETA) - 9:.1f}" '
                 f'text-anchor="end">true effect</text>')
    # Legend and axis label.
    parts.append(f'<circle cx="{LEFT + 6}" cy="13" r="5.6" fill="{RED}" />'
                 f'<text class="hero-legend" x="{LEFT + 18}" y="19">statistically significant</text>'
                 f'<text class="hero-legend" x="{W - RIGHT}" y="19" text-anchor="end">not significant</text>'
                 f'<circle class="hero-legend-ring" cx="{W - RIGHT}" cy="13" r="3.6" fill="none" '
                 f'stroke="{GRAY}" stroke-width="1.5" />')
    parts.append(f'<text class="hero-tick" x="{W - RIGHT}" y="{H - 12}" text-anchor="end">'
                 f'{N} replications of the same study →</text>')

    wrong_text = (f", and {wrong} of them {'points' if wrong == 1 else 'point'} the wrong way" if wrong else "")
    caption = (f"Only {k} of these {N} studies cross the significance cutoff. Those eye-catching "
               f"estimates average {ratio:.1f} times the true effect{wrong_text}.")
    desc = (f"A scatter of {N} replications of one study. The true effect is {THETA}. "
            f"{k} estimates are statistically significant; all are far from the true effect.")
    svg = (f'<svg class="hero-svg" viewBox="0 0 {W} {H}" role="img" aria-labelledby="hero-title hero-desc">'
           f'<title id="hero-title">The statistical significance filter, simulated</title>'
           f'<desc id="hero-desc">{desc}</desc>' + "".join(parts) + "</svg>")
    out = ("<!-- Generated by scripts/make_hero.py; don't edit by hand. -->\n```{=html}\n"
           f'<figure class="hero-chart">{svg}<figcaption>{caption}</figcaption></figure>\n```\n')
    open(os.path.join(ROOT, "_hero-chart.md"), "w", encoding="utf-8", newline="\n").write(out)
    print(f"{k} significant of {N}; average {ratio:.2f} times the truth; {wrong} wrong sign")


if __name__ == "__main__":
    main()
